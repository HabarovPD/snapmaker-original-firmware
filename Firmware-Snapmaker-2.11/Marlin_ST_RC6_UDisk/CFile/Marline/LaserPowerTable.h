#define LaserS_To_Percent(val) do{\
	float v = val;\
	if(v <= LaserPowerTable[0])\
		laserPercent = 0;\
	else if(v >= LaserPowerTable[POWER_TABLE_SIZE - 1])\
		laserPercent = 100;\
	else\
	{\
		laserPercent = 100;\
		for(int i = 1;i < POWER_TABLE_SIZE; i++) {\
			if(v < LaserPowerTable[i]) {\
				laserPercent = (v - LaserPowerTable[i - 1]) / (LaserPowerTable[i] - LaserPowerTable[i - 1]) + (i - 1);\
				break;\
			}\
		}\
	}\
}while(0);





