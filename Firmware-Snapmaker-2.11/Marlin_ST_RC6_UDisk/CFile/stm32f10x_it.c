/**
  * @brief  This function handles Hard Fault exception.
  * @param  None
  * @retval None
  */

extern "C"
{
void HardFault_Handler(void)
{
  /* Go to infinite loop when Hard Fault exception occurs */
  while (1)
  {
  	//Trace("HardFault\r\n");
	//Trace("Int Error\r\n");
	TIM1->CCR1 = 0;
	DAC->DHR12R1 = 0;
	TIM1->CCR2 = 0;
	while(1);
  }
}

}
